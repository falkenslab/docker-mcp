// Writes the tools reference (content/reference/tools.md, and its Spanish page) from the built server's
// own tools/list, so it can't drift from the code. Needs `npm run build` at the root first.
//   node scripts/tools-reference.mjs
// The tools' titles and descriptions are the ones the agent reads, in English on both pages.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "../../node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js";
import { StdioClientTransport } from "../../node_modules/@modelcontextprotocol/sdk/dist/esm/client/stdio.js";

const SERVER = fileURLToPath(new URL("../../dist/server.mjs", import.meta.url));
const OUT = {
  en: fileURLToPath(new URL("../content/reference/tools.md", import.meta.url)),
  es: fileURLToPath(new URL("../i18n/es/docusaurus-plugin-content-docs/current/reference/tools.md", import.meta.url)),
};
const TEXT = {
  en: {
    title: "Tools",
    intro: (n) => `This server has **${n} tools**. This page is generated from the server itself, so it lists them exactly as your AI app gets them, with the descriptions the agent reads. You don't call tools yourself: you ask in your own words, and the agent picks them.`,
    head: ["Tool", "What it does", "Only reads"],
    inputs: "Inputs",
    params: ["Input", "Required", "Type", "Description"],
    none: "No inputs.",
  },
  es: {
    title: "Herramientas",
    intro: (n) => `Este servidor tiene **${n} herramientas**. Esta página se genera a partir del propio servidor, así que las muestra tal como las recibe tu aplicación de IA, con las descripciones que lee el agente, en inglés. Tú no llamas a las herramientas: pides lo que necesitas con tus palabras, y el agente las elige.`,
    head: ["Herramienta", "Qué hace", "Solo lee"],
    inputs: "Entradas",
    params: ["Entrada", "Obligatoria", "Tipo", "Descripción"],
    none: "Sin entradas.",
  },
};

const client = new Client({ name: "tools-reference", version: "0.0.0" });
await client.connect(new StdioClientTransport({ command: process.execPath, args: [SERVER], stderr: "ignore" }));
const { tools } = await client.listTools();
await client.close();

const cell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ").replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`);
const typeOf = (schema) => (schema?.enum ? schema.enum.map((v) => `\`${v}\``).join(", ") : schema?.type === "array" ? `${schema.items?.type ?? "value"} list` : (schema?.type ?? ""));

for (const [lang, t] of Object.entries(TEXT)) {
  const lines = ["---", `title: ${t.title}`, `sidebar_label: ${t.title}`, "---", "", "<!-- Generated by docs/scripts/tools-reference.mjs from the server's tools/list: don't edit by hand. -->", "", `# ${t.title}`, "", t.intro(tools.length), ""];
  lines.push(`| ${t.head.join(" | ")} |`, "| --- | --- | :-: |");
  for (const tool of tools) lines.push(`| [\`${tool.name}\`](#${tool.name.replace(/_/g, "-")}) | ${cell(tool.title)} | ${tool.annotations?.readOnlyHint ? "✓" : ""} |`);
  for (const tool of tools) {
    lines.push("", `## \`${tool.name}\` {#${tool.name.replace(/_/g, "-")}}`, "", `**${cell(tool.title)}**`, "", cell(tool.description), "");
    const properties = Object.entries(tool.inputSchema?.properties ?? {});
    if (!properties.length) {
      lines.push(`*${t.none}*`);
      continue;
    }
    const required = new Set(tool.inputSchema?.required ?? []);
    lines.push(`| ${t.params.join(" | ")} |`, "| --- | :-: | --- | --- |");
    for (const [name, schema] of properties) lines.push(`| \`${name}\` | ${required.has(name) ? "✅" : ""} | ${typeOf(schema)} | ${cell(schema.description)} |`);
  }
  mkdirSync(dirname(OUT[lang]), { recursive: true });
  writeFileSync(OUT[lang], `${lines.join("\n")}\n`);
}
console.log(`tools reference: ${tools.length} tools, in English and Spanish.`);
